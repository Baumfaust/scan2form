"""Desktop entry point: scan2form-gui [file]"""

from __future__ import annotations

import sys
from importlib.resources import files
from pathlib import Path

from PySide6.QtGui import QIcon
from PySide6.QtWidgets import QApplication

from scan2form.ui.main_window import MainWindow

APP_ID = "Scan2Form.Desktop"
ICON_SIZES = (16, 20, 24, 32, 40, 48, 64, 128, 256, 512)  # generated by tools/make_icon.py


def app_icon() -> QIcon:
    assets = files("scan2form.ui") / "assets"
    icon = QIcon()
    for size in ICON_SIZES:
        icon.addFile(str(assets / f"icon-{size}.png"))
    return icon


def _set_windows_app_id() -> None:
    """Without its own AppUserModelID, Windows shows python.exe's icon in the taskbar."""
    if sys.platform == "win32":
        import ctypes

        ctypes.windll.shell32.SetCurrentProcessExplicitAppUserModelID(APP_ID)


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv if argv is None else argv
    if len(argv) > 1 and argv[1] == "--self-test":
        from scan2form import selftest

        return selftest.run(Path(argv[2]) if len(argv) > 2 else None)
    _set_windows_app_id()
    app = QApplication(argv)
    app.setApplicationName("Scan2Form")
    app.setStyle("Fusion")
    app.setWindowIcon(app_icon())
    window = MainWindow()
    window.show()
    if len(argv) > 1:
        window.open_path(Path(argv[1]))
    return app.exec()


if __name__ == "__main__":
    raise SystemExit(main())
